// Keep the insert-only database baseline aligned with the 2027 public fallback.
// Existing production rows and published documents are never changed by seeding.
const fs = require('fs');
const path = require('path');
const ts = require('typescript');
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), {
  compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022 },
}).outputText, filename);
const { createDefaultCpilsContentConfig } = require('../src/app/pages/philippines/cpils-school/cpils-content-config.ts');
const config = createDefaultCpilsContentConfig();
const aliases = {
  'premier-sparta': 'Premier Sparta', 'toeic-course': 'TOEIC Course', 'toeic-guarantee': 'TOEIC Guarantee',
  'ielts-course': 'IELTS Course', 'ielts-guarantee-8-weeks': 'IELTS Guarantee 8 Weeks', 'ielts-guarantee-12-weeks': 'IELTS Guarantee 12 Weeks',
  'power-speaking-and-modern-communication': 'Power Speaking and Modern Communication',
};
const quote = value => JSON.stringify(value);
const lines = ['      // CPILS 2027 baseline; generated by scripts/sync-cpils-seed.cjs.',
  '      // Dates and grandfathered 2026 prices live in the versioned employee document.',
  '      const string cpilsLessonNote = "CPILS 2027年价格；2026/09/29起报名且2027年开课适用，旧报名价格按官网日期政策确认";'];
for (const course of config.courses) {
  const prices = { ...course.feeByWeeks2027 };
  if (course.tuition2027 > 0) prices[4] = course.tuition2027;
  for (const [weeks, price] of Object.entries(prices)) lines.push(`      UpsertLesson(context, schoolId, ${quote(aliases[course.id] || course.name)}, ${weeks}, ${price}m, ${quote([course.schedule, course.suitable].filter(Boolean).join('；'))}, now, cpilsLessonNote);`);
}
for (const room of config.rooms) for (const [weeks, price] of Object.entries({ ...room.feeByWeeks2027, 4: room.fee2027 })) {
  lines.push(`      UpsertRoom(context, schoolId, ${quote(room.name)}, ${weeks}, ${price}m, ${quote(room.note)}, now);`);
}
lines.push('      UpsertFee(context, schoolId, "注册费", 125m, UsdCurrencyId, "一次性报名注册费；老学员返校免收", now);',
  '      UpsertFee(context, schoolId, "旺季附加费", 40m, UsdCurrencyId, "2027/07/05–08/29学习周收取40美元/周；官网使用对应周日入住日期", now);');
for (const fee of config.localFees) {
  const amount = fee.futureAmount ?? fee.amount;
  lines.push(`      UpsertFee(context, schoolId, ${quote(fee.futureName || fee.name)}, ${amount}m, PhpCurrencyId, ${quote(fee.futureNote || fee.note)}, now);`);
}
const file = path.resolve(__dirname, '../../XiaoJuanSchoolPayment.Server/Services/DataInitialize.cs');
const source = fs.readFileSync(file, 'utf8');
const from = source.indexOf('      var schoolId = school.Id;', source.indexOf('private static async Task SeedCpilsPricingAsync')) + '      var schoolId = school.Id;'.length;
const to = source.indexOf('      await context.SaveChangesAsync();', from);
const eol = source.includes('\r\n') ? '\r\n' : '\n';
const updated = source.slice(0, from) + eol + lines.join(eol) + eol + eol + source.slice(to);
if (process.argv.includes('--check')) {
  if (source !== updated) { console.error('CPILS seed does not match the public 2027 defaults.'); process.exit(1); }
  console.log('CPILS 2027 seed matches the public defaults.');
} else { fs.writeFileSync(file, updated); console.log('Updated insert-only CPILS 2027 seed.'); }
